#!/usr/bin/env node
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const apiRoot = path.resolve(__dirname, '..')
const routesRoot = path.join(apiRoot, 'src/http/routes')
const outputFile = path.join(apiRoot, 'src/http/route-registry.ts')

const DYNAMIC_SEGMENT = /^\[(.+)\]$/

/**
 * @param {string} dir
 * @param {{ pattern: string; fs: string }[]} baseSegments
 */
function walkRouteFiles(dir, baseSegments = []) {
  const entries = fs.readdirSync(dir, { withFileTypes: true })
  /** @type {{ segments: string[]; importPath: string }[]} */
  const routes = []

  for (const entry of entries) {
    const fullPath = path.join(dir, entry.name)

    if (entry.isDirectory()) {
      const dynamicMatch = entry.name.match(DYNAMIC_SEGMENT)
      const nextSegments = [
        ...baseSegments,
        {
          pattern: dynamicMatch ? `:${dynamicMatch[1]}` : entry.name,
          fs: entry.name,
        },
      ]
      routes.push(...walkRouteFiles(fullPath, nextSegments))
      continue
    }

    if (entry.isFile() && entry.name === 'route.ts') {
      const importPath = path
        .posix.join('routes', ...baseSegments.map((s) => s.fs), 'route')
        .replace(/\\/g, '/')

      routes.push({
        segments: baseSegments.map((s) => s.pattern),
        importPath,
      })
    }
  }

  return routes
}

/** @param {{ segments: string[]; importPath: string }[]} entries */
function toSource(entries) {
  const serialized = entries
    .sort((a, b) => a.importPath.localeCompare(b.importPath))
    .map((entry) => {
      const segmentsLiteral = JSON.stringify(entry.segments)
      return `  {\n    segments: ${segmentsLiteral},\n    importPath: '${entry.importPath}',\n  }`
    })
    .join(',\n')

  return `/* eslint-disable */
// Auto-generated by scripts/generate-route-registry.mjs — do not edit manually.

export type RouteEntry = {
  segments: string[]
  importPath: string
}

export const ROUTE_ENTRIES: RouteEntry[] = [
${serialized}
]
`
}

if (!fs.existsSync(routesRoot)) {
  console.error(`Routes directory not found: ${routesRoot}`)
  process.exit(1)
}

const entries = walkRouteFiles(routesRoot)
fs.writeFileSync(outputFile, toSource(entries), 'utf8')
console.log(`Wrote ${entries.length} routes to ${path.relative(apiRoot, outputFile)}`)
